"""Create deterministic responsive WebP copies; canonical photos remain unchanged.

Development-only tool: python -m pip install Pillow, then run this script.
The application has no Python dependency at runtime.
"""
from pathlib import Path
from hashlib import sha256
from io import BytesIO
import json

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "public"
SOURCES = PUBLIC / "assets" / "models"
OUTPUT = PUBLIC / "assets" / "optimized" / "models"
MANIFEST = PUBLIC / "js" / "data" / "photo-variants.js"
WIDTHS = (240, 480, 960, 1440)
QUALITY = 88


def main():
    manifest = {}
    source_bytes = largest_bytes = all_bytes = 0
    covers_source = covers_largest = 0
    count = 0
    for source in sorted(SOURCES.glob("*/*")):
        if not source.is_file() or source.suffix.lower() not in (".png", ".jpeg", ".jpg"):
            continue
        data = source.read_bytes()
        # Encoding settings are part of the fingerprint so changed copies have new URLs.
        digest = sha256(data + f"webp-q{QUALITY}-v1".encode()).hexdigest()[:12]
        with Image.open(source) as opened:
            image = ImageOps.exif_transpose(opened).convert("RGB")
            width, height = image.size
            maximum = min(width, max(WIDTHS))
            widths = sorted({size for size in WIDTHS if size <= maximum} | {maximum})
            variants = []
            for size in widths:
                resized = image.resize((size, round(height * size / width)), Image.Resampling.LANCZOS)
                target = OUTPUT / source.parent.name / f"{source.stem}-{digest}-{size}.webp"
                target.parent.mkdir(parents=True, exist_ok=True)
                buffer = BytesIO()
                resized.save(buffer, "WEBP", quality=QUALITY, method=6)
                encoded = buffer.getvalue()
                selected = target
                selected_bytes = len(encoded)
                # A JPEG that is already efficient should not become a larger WebP.
                if size == width and selected_bytes >= len(data):
                    selected = source
                    selected_bytes = len(data)
                else:
                    target.write_bytes(encoded)
                variants.append({"src": "/" + selected.relative_to(PUBLIC).as_posix(), "width": size})
                all_bytes += selected_bytes
            largest = selected_bytes
            source_bytes += len(data)
            largest_bytes += largest
            if source.stem == "cover":
                covers_source += len(data)
                covers_largest += largest
            key = "/" + source.relative_to(PUBLIC).as_posix()
            manifest[key] = {"width": width, "height": height, "sources": variants}
            count += 1
    MANIFEST.write_text(
        "// Generated by scripts/optimize-images.py. Do not edit by hand.\n"
        + "export const photoVariants = " + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(json.dumps({"photos": count, "sourceBytes": source_bytes, "largestVariantBytes": largest_bytes,
                      "allVariantBytes": all_bytes, "coverSourceBytes": covers_source,
                      "coverLargestVariantBytes": covers_largest}))


if __name__ == "__main__":
    main()
